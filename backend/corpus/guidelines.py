def materialize(dest_dir: str | Path | None = None) -> list[Path]:
    """把内置知识库文档写到磁盘（幂等，已存在则跳过）。"""
    root = Path(dest_dir or settings.KNOWLEDGE_DIR)
    root.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for src in SOURCES:
        path = root / f"{src.title}.md"
        if path.exists():
            continue
        path.write_text(src.content, encoding="utf-8")
        written.append(path)
    if written:
        logger.info("知识库内置文档已生成：%d 个", len(written))
    return written


def to_chunks() -> list[Chunk]:
    """内置知识库 → 检索 chunk。"""
    chunks: list[Chunk] = []
    for src in SOURCES:
        chunks.extend(
            chunk_knowledge(
                src.content,
                title=src.title,
                doc_type=src.doc_type,
                version=src.version,
                category=src.category,
                effective_date=src.effective_date,
                source_path=f"builtin://{src.title}",
            )
        )
    return chunks
